"""
Runtime texture registry: loads per-palette texture sheets
(assets/textures/<palette>/<kind>.png, described by the palette JSON in
assets/palettes/) and serves cached tile sub-surfaces to the renderer.
The registry is data-driven -- textures are generated by
tools/build_textures.py and referenced by the palette JSON, never
hardcoded per zone in code.
"""

from __future__ import annotations

import json
from pathlib import Path

import pygame

ROOT = Path(__file__).resolve().parent.parent.parent

KINDS = ("solid", "oneway", "spring", "crumble")


class TextureRegistry:
    """Lazy loader/cache over palette JSON + sheet PNGs.

    get() returns (Surface, y_offset); blit at (px, py + y_offset)."""

    def __init__(self, palettes_dir: Path, textures_dir: Path):
        self.palettes_dir = Path(palettes_dir)
        self.textures_dir = Path(textures_dir)
        self._palettes = {}
        self._sheets = {}
        self._cells = {}
        self._dark = {}
        self._miss = set()
        self._missing_surf = None

    def palette_names(self) -> list:
        """Sorted palette labels (from the palette JSON filenames)."""
        return sorted(p.name[:-5] for p in self.palettes_dir.glob("*.json"))

    def _load_palette(self, name: str):
        if name not in self._palettes:
            path = self.palettes_dir / f"{name}.json"
            self._palettes[name] = json.loads(path.read_text()) if path.exists() else None
        return self._palettes[name]

    def _target(self, palette: str, kind: str, warned_key):
        """Resolve (palette_name, palette_dict, spec_dict) after fallbacks,
        or None for a missing texture. Warns once per requested key."""
        current = palette if palette else "default"
        while True:
            pal = self._load_palette(current)
            spec = pal.get("textures", {}).get(kind) if pal else None
            path = None
            if spec is not None:
                path = self.textures_dir / current / spec["file"]
            if pal is not None and spec is not None and path.exists():
                return current, pal, spec
            if current == "default":
                break
            if warned_key not in self._miss:
                self._miss.add(warned_key)
                print(f"[texture_registry] missing {kind!r} texture for palette "
                      f"{palette!r}; using default")
            current = "default"
        if warned_key not in self._miss:
            self._miss.add(warned_key)
            print(f"[texture_registry] missing {kind!r} texture for palette {palette!r}")
        return None

    def _sheet_image(self, name: str, pal: dict, kind: str):
        key = (name, kind)
        hit = self._sheets.get(key)
        if hit is not None:
            return hit
        spec = pal["textures"][kind]
        img = pygame.image.load(self.textures_dir / name / spec["file"])
        if pygame.display.get_surface() is not None:
            img = img.convert_alpha()
        self._sheets[key] = img
        return img

    def _cell(self, name: str, pal: dict, kind: str, spec: dict, mask, variant, tick, stage):
        """(Surface, y_offset, cache_key) for one sheet cell."""
        layout = spec.get("layout")
        tile_px = pal.get("tile_px", 48)
        if layout == "autotile16":
            col = variant % max(1, spec.get("variants", 1))
            row = max(0, min(15, mask))
            overhang = spec.get("overhang_px", 0)
            ch = tile_px + overhang
            key = (name, kind, row, col)
            hit = self._cells.get(key)
            if hit is not None:
                return hit
            sheet = self._sheet_image(name, pal, kind)
            surf = sheet.subsurface((col * tile_px, row * ch, tile_px, ch))
            result = (surf, -overhang, key)
            self._cells[key] = result
            return result
        if layout == "frames":
            frames = max(1, spec.get("frames", 1))
            frame_ticks = max(1, spec.get("frame_ticks", 1))
            col = (tick // frame_ticks) % frames
            row = 0
        elif layout == "stages":
            stages = max(1, spec.get("stages", 1))
            row = 0
            col = max(0, min(stages - 1, stage))
        else:  # "variants" and anything square-ish
            row = 0
            col = variant % max(1, spec.get("variants", 1))
        key = (name, kind, row, col)
        hit = self._cells.get(key)
        if hit is not None:
            return hit
        sheet = self._sheet_image(name, pal, kind)
        surf = sheet.subsurface((col * tile_px, row * tile_px, tile_px, tile_px))
        result = (surf, 0, key)
        self._cells[key] = result
        return result

    def _darkened(self, surf, cache_key, shade: float):
        shade_r = round(shade, 2)
        key = (*cache_key, shade_r)
        hit = self._dark.get(key)
        if hit is not None:
            return hit
        v = int(255 * shade_r)
        copy = surf.copy()
        copy.fill((v, v, v), special_flags=pygame.BLEND_RGB_MULT)
        self._dark[key] = copy
        return copy

    def _missing(self):
        if self._missing_surf is None:
            surf = pygame.Surface((48, 48), pygame.SRCALPHA)
            for y in range(48):
                for x in range(48):
                    surf.set_at((x, y), (255, 0, 255) if ((x // 8) + (y // 8)) % 2 else (0, 0, 0))
            self._missing_surf = surf
        return self._missing_surf

    def get(self, palette, kind, *, mask=15, variant=0, tick=0, stage=0,
            shade=1.0) -> tuple:
        """(Surface, y_offset) for one tile texture; blit at (px, py + y_offset)."""
        target = self._target(palette, kind, (palette, kind))
        if target is None:
            surf, y_off = self._missing(), 0
        else:
            name, pal, spec = target
            surf, y_off, cell_key = self._cell(name, pal, kind, spec, mask, variant, tick, stage)
        if shade < 1.0:
            surf = self._darkened(surf, cell_key, shade)
        return surf, y_off


_DEFAULT = None


def default_registry() -> TextureRegistry:
    """Module-level singleton registry built from ROOT/assets."""
    global _DEFAULT
    if _DEFAULT is None:
        _DEFAULT = TextureRegistry(ROOT / "assets" / "palettes",
                                   ROOT / "assets" / "textures")
    return _DEFAULT
