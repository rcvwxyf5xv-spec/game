"""Runtime sprite registry: loads per-sprite sheets (assets/sprites/<name>.png
+ <name>.json, generated by tools/build_sprites.py) and serves cached,
anchor-aware, optionally mirrored frames to the renderer.

The registry is data-driven -- sprites are built from the hand-editable
definitions in assets/sprite_src/. Missing sprites/animations degrade to a
one-time-warned magenta placeholder instead of crashing.
"""

from __future__ import annotations

import json
from pathlib import Path

import pygame

MAGENTA = (255, 0, 255)


class SpriteRegistry:
    """Lazy loader/cache over sprite sheets + metadata JSONs.

    get_frame() returns (Surface, anchor_x, anchor_y): blit the surface so
    (anchor_x, anchor_y) sits at the sprite's base point (feet bottom-center
    for the player, base bottom-center for the save station)."""

    def __init__(self, sprites_dir: Path):
        self.sprites_dir = Path(sprites_dir)
        self._metas = {}
        self._sheets = {}
        self._frames = {}
        self._miss = set()

    def _load_meta(self, name: str):
        if name not in self._metas:
            path = self.sprites_dir / f"{name}.json"
            self._metas[name] = json.loads(path.read_text()) if path.exists() else None
        return self._metas[name]

    def _load_sheet(self, name: str, meta: dict):
        hit = self._sheets.get(name)
        if hit is not None:
            return hit
        img = pygame.image.load(self.sprites_dir / f"{name}.png")
        if pygame.display.get_surface() is not None:
            img = img.convert_alpha()
        self._sheets[name] = img
        return img

    def frame_count(self, name, anim):
        meta = self._load_meta(name)
        anim_spec = meta["animations"].get(anim) if meta else None
        if anim_spec is None:
            return 1
        return anim_spec["count"]

    def _frame(self, name, frame_w, frame_h, index):
        key = (name, index)
        hit = self._frames.get(key)
        if hit is not None:
            return hit
        meta = self._metas[name]
        sheet = self._load_sheet(name, meta)
        surf = sheet.subsurface((index * frame_w, 0, frame_w, frame_h))
        self._frames[key] = surf
        return surf

    def get_frame(self, name, anim, tick_or_index, facing=1, by_tick=True):
        """(Surface, anchor_x, anchor_y) for one animation frame. With
        by_tick=True the frame index is (tick_or_index // frame_ticks) %
        count; otherwise tick_or_index % count. facing < 0 mirrors the
        frame and its anchor horizontally."""
        meta = self._load_meta(name)
        if meta is None or anim not in meta.get("animations", {}):
            self._warn_missing(name, anim)
            return self._placeholder(name, anim)
        anim_spec = meta["animations"][anim]
        count = anim_spec["count"]
        if by_tick:
            index = (tick_or_index // max(1, anim_spec.get("frame_ticks", 1))) % count
        else:
            index = tick_or_index % count
        frame_w = meta["frame_w"]
        frame_h = meta["frame_h"]
        surf = self._frame(name, frame_w, frame_h, anim_spec["start"] + index)
        ax, ay = meta["anchor_px"]
        if facing < 0:
            surf = pygame.transform.flip(surf, True, False)
            ax = frame_w - 1 - ax
        return surf, ax, ay

    # -- placeholders ---------------------------------------------------------

    def _warn_missing(self, name, anim):
        key = (name, anim)
        if key in self._miss:
            return
        self._miss.add(key)
        print(f"[sprite_registry] missing sprite/animation {name!r}/{anim!r}; "
              f"using magenta placeholder")

    def _placeholder(self, name, anim):
        meta = self._load_meta(name)
        if meta is not None:
            w, h = meta["frame_w"], meta["frame_h"]
        else:
            w, h = 24, 24
        surf = pygame.Surface((w, h), pygame.SRCALPHA)
        surf.fill((255, 255, 255, 0))
        for y in range(0, h, 8):
            for x in range(0, w, 8):
                if (x // 8 + y // 8) % 2:
                    surf.fill((0, 0, 0), (x, y, min(8, w - x), min(8, h - y)))
        pygame.draw.rect(surf, MAGENTA, (0, 0, w, h), 2)
        return surf, w // 2, h - 1


_DEFAULT = None


def default_sprites() -> SpriteRegistry:
    """Module-level singleton registry for the active project's sprites."""
    from src.project import active

    global _DEFAULT
    if _DEFAULT is None:
        _DEFAULT = SpriteRegistry(active().sprites_dir)
    return _DEFAULT
